#!/usr/bin/env bash
# Render the Homebrew formula for a memdusa release from its checksum files.
#
#   packaging/homebrew/render-formula.sh <version> <dir-with-sha256-files> [owner/repo]
#
# <dir> must contain the release's `memdusa-v<version>-<target>.tar.gz.sha256`
# files (as published next to each archive). The release workflow runs this and
# pushes the result to the tap (github.com/<owner>/homebrew-tap).
set -euo pipefail

version="${1:?usage: render-formula.sh <version> <dir> [owner/repo]}"
dir="${2:?usage: render-formula.sh <version> <dir> [owner/repo]}"
repo="${3:-Krishnacore/memdusa}"
version="${version#v}"

sha() {
  local file="$dir/memdusa-v$version-$1.tar.gz.sha256"
  [[ -f "$file" ]] || { echo "missing $file" >&2; exit 1; }
  local value
  value="$(cut -d' ' -f1 < "$file")"
  [[ "$value" =~ ^[0-9a-f]{64}$ ]] || { echo "bad checksum in $file" >&2; exit 1; }
  echo "$value"
}

url() { echo "https://github.com/$repo/releases/download/v$version/memdusa-v$version-$1.tar.gz"; }

# Resolve every checksum up front: a failure inside the heredoc's $(...) would
# only end a subshell, not this script.
mac_arm="$(sha aarch64-apple-darwin)"
mac_intel="$(sha x86_64-apple-darwin)"
linux_arm="$(sha aarch64-unknown-linux-gnu)"
linux_intel="$(sha x86_64-unknown-linux-gnu)"

cat <<EOF
# Generated by packaging/homebrew/render-formula.sh in $repo for v$version. Do not edit by hand.
class Memdusa < Formula
  desc "Memory & durability for AI agents and coding harnesses"
  homepage "https://github.com/$repo"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$(url aarch64-apple-darwin)"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$(url x86_64-apple-darwin)"
      sha256 "$mac_intel"
    end
  end

  on_linux do
    on_arm do
      url "$(url aarch64-unknown-linux-gnu)"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$(url x86_64-unknown-linux-gnu)"
      sha256 "$linux_intel"
    end
  end

  def install
    bin.install "memdusa"
    doc.install "README.md"
    prefix.install "LICENSE", "NOTICE" if File.exist?("LICENSE")
  end

  def caveats
    <<~EOS
      Connect your harness, e.g.:
        memdusa install claude-code
      Other harnesses: codex, cursor, antigravity, gemini, opencode, pi, hermes, git.
    EOS
  end

  test do
    assert_match "memdusa #{version}", shell_output("#{bin}/memdusa --version")
    db = "sqlite:#{testpath}/t.db"
    system bin/"memdusa", "--database-url", db, "--project", "brew/test", "remember", "brew works"
    assert_match "brew works", shell_output("#{bin}/memdusa --database-url #{db} --project brew/test recall")
  end
end
EOF
